#!/usr/bin/env node
/**
 * Derives a Bruno collection from the IntelliJ HTTP Client requests.
 *
 * The .http files in httpRequests/ stay the source of truth. This script only
 * translates the mechanical parts (method, URL, headers, body, sequence) and
 * maps the IntelliJ scripting API to Bruno's scripting API.
 *
 * Usage (from httpRequests/bruno):
 *   node tools/http-to-bru.mjs --source ../restRequest
 *   node tools/http-to-bru.mjs --source ../restRequest --check
 *   node tools/http-to-bru.mjs --source ../restRequest --format bru --collection /tmp/bruno-bru
 */

import { mkdir, readFile, readdir, rm, stat, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const COLLECTION_ROOT = path.resolve(SCRIPT_DIR, '..');
const REQUESTS_ROOT = path.resolve(COLLECTION_ROOT, '..');
const MARKER = 'Generated by tools/http-to-bru.mjs';
const HTTP_METHODS = new Set(['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS']);
const TRACEPARENT_SCRIPT = 'traceparent.js';
const AUTH_HEADER_PATTERN = /^Bearer\s+\{\{\$auth\.token\("([^"]+)"\)\}\}$/i;
const FORMATS = new Set(['bru', 'yml']);
const require = createRequire(import.meta.url);
let filestore;

function usage(message, exitCode = 1) {
  if (message) {
    console.error(`${message}\n`);
  }
  console.error(
    [
      'Usage: node tools/http-to-bru.mjs [options]',
      '',
      'Options:',
      '  --source <path>      .http file or directory to convert (default: ../restRequest)',
      '  --collection <path>  Target collection root (default: parent of tools/)',
      '  --format <bru|yml>   Output format (default: yml)',
      '  --check              Do not write; exit 1 when generated files differ',
      '  -h, --help           Show this help',
    ].join('\n'),
  );
  process.exit(exitCode);
}

function parseArgs(argv) {
  const args = { source: path.join(REQUESTS_ROOT, 'restRequest'), collection: COLLECTION_ROOT, format: 'yml', check: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--source') {
      args.source = path.resolve(process.cwd(), argv[++i] ?? '');
    } else if (arg === '--collection') {
      args.collection = path.resolve(process.cwd(), argv[++i] ?? '');
    } else if (arg === '--format') {
      args.format = argv[++i] ?? '';
      if (!FORMATS.has(args.format)) {
        usage(`Unsupported format: ${args.format}`);
      }
    } else if (arg === '--check') {
      args.check = true;
    } else if (arg === '-h' || arg === '--help') {
      usage(null, 0);
    } else {
      usage(`Unknown argument: ${arg}`);
    }
  }
  return args;
}

async function collectHttpFiles(source) {
  const info = await stat(source);
  if (info.isFile()) {
    return [source];
  }
  const entries = await readdir(source, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const entryPath = path.join(source, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectHttpFiles(entryPath)));
    } else if (entry.isFile() && entry.name.endsWith('.http')) {
      files.push(entryPath);
    }
  }
  return files;
}

function splitTopLevel(text) {
  const parts = [];
  let current = '';
  let depth = 0;
  let quote = null;
  for (let i = 0; i < text.length; i += 1) {
    const char = text[i];
    if (quote) {
      current += char;
      if (char === '\\') {
        current += text[++i] ?? '';
      } else if (char === quote) {
        quote = null;
      }
      continue;
    }
    if (char === '"' || char === "'" || char === '`') {
      quote = char;
      current += char;
    } else if (char === '(' || char === '[' || char === '{') {
      depth += 1;
      current += char;
    } else if (char === ')' || char === ']' || char === '}') {
      depth -= 1;
      current += char;
    } else if (char === ',' && depth === 0) {
      parts.push(current.trim());
      current = '';
    } else {
      current += char;
    }
  }
  if (current.trim() || parts.length > 0) {
    parts.push(current.trim());
  }
  return parts;
}

function findMatchingParen(text, openIndex) {
  let depth = 0;
  let quote = null;
  for (let i = openIndex; i < text.length; i += 1) {
    const char = text[i];
    if (quote) {
      if (char === '\\') {
        i += 1;
      } else if (char === quote) {
        quote = null;
      }
      continue;
    }
    if (char === '"' || char === "'" || char === '`') {
      quote = char;
    } else if (char === '(') {
      depth += 1;
    } else if (char === ')') {
      depth -= 1;
      if (depth === 0) {
        return i;
      }
    }
  }
  return -1;
}

function convertClientAsserts(script) {
  const needle = 'client.assert(';
  let result = '';
  let offset = 0;
  while (true) {
    const index = script.indexOf(needle, offset);
    if (index === -1) {
      result += script.slice(offset);
      return result;
    }
    result += script.slice(offset, index);
    const openIndex = index + needle.length - 1;
    const closeIndex = findMatchingParen(script, openIndex);
    if (closeIndex === -1) {
      result += script.slice(index);
      return result;
    }
    const args = splitTopLevel(script.slice(openIndex + 1, closeIndex));
    const condition = args[0] || 'false';
    const message = args[1];
    result += message
      ? `expect(${condition}, ${message}).to.be.true;`
      : `expect(${condition}).to.be.true;`;
    offset = script[closeIndex + 1] === ';' ? closeIndex + 2 : closeIndex + 1;
  }
}

function indentBlock(text) {
  return text
    .split('\n')
    .map((line) => (line === '' ? '' : `  ${line}`))
    .join('\n');
}

function dedent(text) {
  const lines = text.split('\n');
  const indents = lines.filter((line) => line.trim() !== '').map((line) => line.match(/^\s*/)[0].length);
  const minimum = indents.length > 0 ? Math.min(...indents) : 0;
  return lines.map((line) => (line.trim() === '' ? '' : line.slice(minimum))).join('\n');
}

function translateScript(script) {
  if (!script) {
    return '';
  }
  let translated = dedent(script);
  translated = translated.replace(/\bclient\.log\(/g, 'console.log(');
  translated = translated.replace(/\bclient\.global\.set\(/g, 'bru.setVar(');
  translated = translated.replace(/\bclient\.global\.get\(/g, 'bru.getVar(');
  translated = translated.replace(/\brequest\.variables\.set\(/g, 'bru.setVar(');
  translated = translated.replace(/(?<![\w.$])response\.headers\.valueOf\(/g, 'res.getHeader(');
  translated = translated.replace(/(?<![\w.$])response\.status\b/g, 'res.status');
  translated = translated.replace(/(?<![\w.$])response\.body\b/g, 'res.body');
  translated = translated.replace(/\bclient\.test\(/g, 'test(');
  translated = convertClientAsserts(translated);
  return translated.trim();
}

function isHeaderLine(line) {
  return /^[A-Za-z0-9!#$%&'*+\-.^_`|~]+:\s*.*$/.test(line);
}

function readBlock(lines, startIndex, closingTag) {
  const collected = [];
  let index = startIndex;
  while (index < lines.length) {
    const line = lines[index];
    if (line.trim() === closingTag) {
      return { content: collected.join('\n'), nextIndex: index + 1 };
    }
    collected.push(line);
    index += 1;
  }
  return { content: collected.join('\n'), nextIndex: index };
}

function parseRequestBlock(title, lines) {
  const state = { comments: [], includes: [], postIncludes: [], preScripts: [], headers: [], body: [], postScript: '' };
  let method = null;
  let url = null;
  let bodyStarted = false;
  let index = 0;

  while (index < lines.length) {
    const line = lines[index];
    const trimmed = line.trim();

    if (method === null) {
      if (trimmed === '') {
        index += 1;
        continue;
      }
      if (line.startsWith('#')) {
        state.comments.push(line.replace(/^#\s?/, ''));
        index += 1;
        continue;
      }
      if (trimmed.startsWith('<')) {
        const rest = trimmed.slice(1).trim();
        if (rest.startsWith('{%')) {
          const block = readBlock(lines, index + 1, '%}');
          state.preScripts.push(block.content);
          index = block.nextIndex;
        } else {
          state.includes.push(rest);
          index += 1;
        }
        continue;
      }
      const requestMatch = line.match(/^([A-Z]+)\s+(\S+)\s*$/);
      if (requestMatch && HTTP_METHODS.has(requestMatch[1])) {
        method = requestMatch[1];
        url = requestMatch[2];
        index += 1;
        continue;
      }
      index += 1;
      continue;
    }

    if (trimmed === '') {
      if (bodyStarted) {
        state.body.push('');
      }
      index += 1;
      continue;
    }

    if (trimmed.startsWith('>')) {
      const rest = trimmed.slice(1).trim();
      if (rest.startsWith('{%')) {
        const block = readBlock(lines, index + 1, '%}');
        state.postScript = [state.postScript, block.content].filter(Boolean).join('\n');
        index = block.nextIndex;
      } else {
        state.postIncludes.push(rest);
        index += 1;
      }
      continue;
    }

    if (!bodyStarted && isHeaderLine(line)) {
      const separator = line.indexOf(':');
      state.headers.push([line.slice(0, separator).trim(), line.slice(separator + 1).trim()]);
      index += 1;
      continue;
    }

    bodyStarted = true;
    state.body.push(line);
    index += 1;
  }

  return { title, method, url, ...state };
}

function parseHttpFile(content) {
  const lines = content.replace(/\r\n/g, '\n').split('\n');
  const preamble = [];
  const blocks = [];
  let current = null;

  for (const line of lines) {
    if (/^###(?:\s|$)/.test(line)) {
      if (current) {
        blocks.push(current);
      }
      current = { title: line.replace(/^###\s?/, '').trim(), lines: [] };
      continue;
    }
    if (current) {
      current.lines.push(line);
    } else if (line.startsWith('#')) {
      preamble.push(line.replace(/^#\s?/, ''));
    }
  }
  if (current) {
    blocks.push(current);
  }

  return { preamble, requests: blocks.map((block) => parseRequestBlock(block.title, block.lines)) };
}

function slugify(title, fallback) {
  const cleaned = (title || fallback)
    .replace(/^\d+[a-z]?\)\s*/i, '')
    .replace(/\(.*?\)/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return (cleaned || fallback).slice(0, 60).replace(/-+$/g, '');
}

function normalizeUrl(url) {
  return /^[a-z][a-z0-9+.-]*:\/\//i.test(url) ? url : `http://${url}`;
}

function isJsonBody(headers, body) {
  const contentType = headers.find(([name]) => name.toLowerCase() === 'content-type')?.[1].toLowerCase();
  if (contentType) {
    return contentType.startsWith('application/json');
  }
  const trimmed = body.trim();
  return trimmed.startsWith('{') || trimmed.startsWith('[');
}

function getFilestore() {
  if (!filestore) {
    try {
      filestore = require('@usebruno/filestore');
    } catch (error) {
      throw new Error('Missing dependency @usebruno/filestore. Run "npm install" in httpRequests/bruno/tools.');
    }
  }
  return filestore;
}

function toYaml(content, parser) {
  const library = getFilestore();
  if (parser === 'folder') {
    return withTrailingNewline(library.stringifyFolder(library.parseFolder(content, { format: 'bru' }), { format: 'yml' }));
  }
  if (parser === 'environment') {
    return withTrailingNewline(library.stringifyEnvironment(library.parseEnvironment(content, { format: 'bru' }), { format: 'yml' }));
  }
  return withTrailingNewline(library.stringifyRequest(library.parseRequest(content, { format: 'bru' }), { format: 'yml' }));
}

function withTrailingNewline(text) {
  return text.endsWith('\n') ? text : `${text}\n`;
}

function toYamlCollection(content, config) {
  const library = getFilestore();
  const data = library.parseCollection(content, { format: 'bru' });
  return withTrailingNewline(library.stringifyCollection(data, config, { format: 'yml' }));
}

function encodeBasicAuthorization(value) {
  const match = value.match(/^Basic\s+(\S+)\s+(\S+)$/i);
  if (!match) {
    return value;
  }
  return `Basic ${Buffer.from(`${match[1]}:${match[2]}`).toString('base64')}`;
}

function extractAuthId(request) {
  for (const [name, value] of request.headers) {
    if (name.toLowerCase() !== 'authorization') {
      continue;
    }
    const match = value.match(AUTH_HEADER_PATTERN);
    if (match) {
      return match[1];
    }
  }
  return null;
}

function renderFolderAuth(authId, config, name) {
  return [
    'meta {',
    `  name: ${name}`,
    '  type: folder',
    '}',
    '',
    'auth {',
    '  mode: oauth2',
    '}',
    '',
    'auth:oauth2 {',
    '  grant_type: client_credentials',
    `  access_token_url: ${config.tokenUrl}`,
    '  client_id: {{clientId}}',
    '  client_secret: {{clientSecret}}',
    `  scope: ${config.scope}`,
    `  credentials_placement: ${config.credentialsPlacement}`,
    `  credentials_id: ${authId}`,
    '  token_placement: header',
    '  token_header_prefix: Bearer',
    '  auto_fetch_token: true',
    '  auto_refresh_token: false',
    '}',
    '',
    'docs {',
    `  OAuth2 client credentials (auth ID: ${authId}).`,
    `  ${MARKER}`,
    '}',
    '',
  ].join('\n');
}

async function loadAuthConfigs() {
  const file = path.join(REQUESTS_ROOT, 'http-client.env.json');
  const content = JSON.parse(await readFile(file, 'utf8'));
  const profile = content.local ?? Object.values(content)[0];
  const auth = profile?.Security?.Auth ?? {};
  const configs = new Map();
  for (const [id, value] of Object.entries(auth)) {
    if (value.Type !== 'OAuth2' || value['Grant Type'] !== 'Client Credentials') {
      continue;
    }
    configs.set(id, {
      tokenUrl: value['Token URL'],
      scope: value.Scope,
      credentialsPlacement: value['Client Credentials'] === 'basic' ? 'basic_auth_header' : 'body',
    });
  }
  return configs;
}

function renderRequest(request, sequence, metadata) {
  const filterHeader = (name) => {
    const lower = name.toLowerCase();
    return lower !== 'content-length' && lower !== 'host';
  };
  while (request.body.length > 0 && request.body[request.body.length - 1].trim() === '') {
    request.body.pop();
  }
  const jsonBody = request.body.length > 0 && isJsonBody(request.headers, request.body.join('\n'));
  const headers = request.headers.filter(([name, value]) => {
    if (!filterHeader(name)) {
      return false;
    }
    if (jsonBody && name.toLowerCase() === 'content-type') {
      return false;
    }
    if (name.toLowerCase() === 'authorization' && AUTH_HEADER_PATTERN.test(value)) {
      return false;
    }
    return true;
  });

  const includeContent = request.includes
    .filter((include) => !include.endsWith(TRACEPARENT_SCRIPT))
    .map((include) => translateScript(metadata.includeContents[include] || ''))
    .join('\n');
  const preRequest = [includeContent, ...request.preScripts.map(translateScript)].filter(Boolean).join('\n');
  const tests = translateScript(request.postScript);

  const docs = [...metadata.preamble, ...request.comments].filter(Boolean);
  if (docs.length > 0) {
    docs.push('');
  }
  docs.push(`Source: ${metadata.sourceRelativePath}`);
  docs.push(MARKER);

  const bodyMode = request.body.length === 0 ? 'none' : jsonBody ? 'json' : 'text';
  const out = [];
  out.push('meta {');
  out.push(`  name: ${request.title || `Request ${sequence}`}`);
  out.push('  type: http');
  out.push(`  seq: ${sequence}`);
  out.push('}');
  out.push('');
  out.push(`${request.method.toLowerCase()} {`);
  out.push(`  url: ${normalizeUrl(request.url)}`);
  out.push(`  body: ${bodyMode}`);
  out.push('  auth: inherit');
  out.push('}');

  if (headers.length > 0) {
    out.push('');
    out.push('headers {');
    for (const [name, value] of headers) {
      out.push(`  ${name}: ${name.toLowerCase() === 'authorization' ? encodeBasicAuthorization(value) : value}`);
    }
    out.push('}');
  }

  if (request.body.length > 0) {
    out.push('');
    out.push(`body:${bodyMode} {`);
    out.push(
      request.body
        .map((line) => (line === '' ? '' : `  ${line}`))
        .join('\n'),
    );
    out.push('}');
  }

  if (preRequest) {
    out.push('');
    out.push('script:pre-request {');
    out.push(indentBlock(preRequest));
    out.push('}');
  }

  if (tests) {
    out.push('');
    out.push('tests {');
    out.push(indentBlock(tests));
    out.push('}');
  }

  out.push('');
  out.push('docs {');
  for (const line of docs) {
    out.push(line ? `  ${line}` : '');
  }
  out.push('}');
  out.push('');
  return out.join('\n');
}

function targetDirectoryFor(file, collectionRoot) {
  const relative = path.relative(REQUESTS_ROOT, file).split(path.sep).join('/');
  const withoutExtension = relative.replace(/\.http$/, '');
  const directory = path.posix.dirname(withoutExtension);
  const baseName = path.posix.basename(withoutExtension);
  const parentName = path.posix.basename(directory);
  const targetDirectory = baseName === parentName ? directory : path.posix.join(directory, baseName);
  return { relative, directory: path.join(collectionRoot, targetDirectory) };
}

async function buildExpected(files, collectionRoot, source, format) {
  const expected = new Map();
  const extension = format === 'yml' ? '.yml' : '.bru';
  const authConfigs = await loadAuthConfigs();
  const globalAuthIds = new Set();
  const directoryAuthIds = new Map();
  includeCache.clear();
  for (const file of files) {
    const content = await readFile(file, 'utf8');
    const { preamble, requests } = parseHttpFile(content);
    const { relative, directory } = targetDirectoryFor(file, collectionRoot);
    const parsed = requests.filter((request) => request.method && request.url);
    for (const [index, request] of parsed.entries()) {
      request.authId = extractAuthId(request);
      if (request.authId) {
        if (!authConfigs.has(request.authId)) {
          throw new Error(`Unknown OAuth2 auth ID '${request.authId}' in ${relative}`);
        }
        globalAuthIds.add(request.authId);
        if (!directoryAuthIds.has(directory)) {
          directoryAuthIds.set(directory, new Set());
        }
        directoryAuthIds.get(directory).add(request.authId);
      }
      const sequence = index + 1;
      const fileName = `${String(sequence).padStart(2, '0')}-${slugify(request.title, `request-${sequence}`)}${extension}`;
      const includeContents = {};
      for (const include of request.includes) {
        includeContents[include] = await readIncludeCached(include, file);
      }
      while (request.body.length > 0 && request.body[request.body.length - 1].trim() === '') {
        request.body.pop();
      }
      const bodyInclude = request.body.length === 1 ? request.body[0].trim().match(/^<\s+(\S+)$/) : null;
      if (bodyInclude) {
        const bodyPath = path.resolve(path.dirname(file), bodyInclude[1]);
        request.body = (await readFile(bodyPath, 'utf8')).replace(/\r\n/g, '\n').split('\n');
      }
      const renderedBru = renderRequest(request, sequence, {
        preamble: index === 0 ? preamble : [],
        sourceRelativePath: relative,
        includeContents,
      });
      const rendered = format === 'yml' ? toYaml(renderedBru, 'request') : renderedBru;
      expected.set(path.join(directory, fileName), rendered);
    }
  }

  if (globalAuthIds.size > 0) {
    if (globalAuthIds.size === 1) {
      const [authId] = [...globalAuthIds];
      const serviceRoot = await serviceRootForSource(source, collectionRoot);
      const folderName = format === 'yml' ? 'folder.yml' : 'folder.bru';
      const folderBru = renderFolderAuth(authId, authConfigs.get(authId), path.basename(serviceRoot));
      expected.set(path.join(serviceRoot, folderName), format === 'yml' ? toYaml(folderBru, 'folder') : folderBru);
    } else {
      for (const [directory, authIds] of directoryAuthIds) {
        if (authIds.size !== 1) {
          throw new Error(`Mixed OAuth2 auth IDs in ${path.relative(collectionRoot, directory)}`);
        }
        const [authId] = [...authIds];
        const folderName = format === 'yml' ? 'folder.yml' : 'folder.bru';
        const folderBru = renderFolderAuth(authId, authConfigs.get(authId), path.basename(directory));
        expected.set(path.join(directory, folderName), format === 'yml' ? toYaml(folderBru, 'folder') : folderBru);
      }
    }
  }

  if (format === 'yml') {
    await addYamlCollectionFiles(expected, collectionRoot);
  }

  return expected;
}

async function pathExists(file) {
  try {
    await stat(file);
    return true;
  } catch (error) {
    if (error.code === 'ENOENT') {
      return false;
    }
    throw error;
  }
}

async function addYamlCollectionFiles(expected, collectionRoot) {
  const collectionBruPath = path.join(COLLECTION_ROOT, 'collection.bru');
  const openCollectionPath = path.join(COLLECTION_ROOT, 'opencollection.yml');

  if (await pathExists(collectionBruPath)) {
    const config = JSON.parse(await readFile(path.join(COLLECTION_ROOT, 'bruno.json'), 'utf8'));
    const collectionBru = await readFile(collectionBruPath, 'utf8');
    expected.set(path.join(collectionRoot, 'opencollection.yml'), toYamlCollection(collectionBru, config));
  } else if (await pathExists(openCollectionPath)) {
    expected.set(path.join(collectionRoot, 'opencollection.yml'), await readFile(openCollectionPath, 'utf8'));
  } else {
    throw new Error(`No collection.bru or opencollection.yml found in ${COLLECTION_ROOT}`);
  }

  const environmentDir = path.join(COLLECTION_ROOT, 'environments');
  const entries = await readdir(environmentDir, { withFileTypes: true }).catch((error) => {
    if (error.code === 'ENOENT') {
      return [];
    }
    throw error;
  });
  const bruEntries = entries.filter((entry) => entry.isFile() && entry.name.endsWith('.bru'));
  if (bruEntries.length > 0) {
    for (const entry of bruEntries.sort((a, b) => a.name.localeCompare(b.name))) {
      const content = await readFile(path.join(environmentDir, entry.name), 'utf8');
      const yml = toYaml(content, 'environment');
      expected.set(path.join(collectionRoot, 'environments', entry.name.replace(/\.bru$/, '.yml')), yml);
    }
    return;
  }

  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isFile() || !entry.name.endsWith('.yml')) {
      continue;
    }
    const content = await readFile(path.join(environmentDir, entry.name), 'utf8');
    expected.set(path.join(collectionRoot, 'environments', entry.name), content);
  }
}

async function serviceRootForSource(sourcePath, collectionRoot) {
  const info = await stat(sourcePath);
  if (info.isDirectory()) {
    return path.join(collectionRoot, path.relative(REQUESTS_ROOT, sourcePath));
  }
  return targetDirectoryFor(sourcePath, collectionRoot).directory;
}

const includeCache = new Map();
async function readIncludeCached(includePath, httpFilePath) {
  const resolved = path.resolve(path.dirname(httpFilePath), includePath);
  if (!includeCache.has(resolved)) {
    includeCache.set(resolved, await readFile(resolved, 'utf8'));
  }
  return includeCache.get(resolved);
}

async function ownedRootForSource(sourcePath, collectionRoot) {
  const relative = path.relative(REQUESTS_ROOT, sourcePath);
  if (relative.startsWith('..') || path.isAbsolute(relative)) {
    throw new Error(`Source must be inside ${REQUESTS_ROOT}: ${sourcePath}`);
  }
  const info = await stat(sourcePath);
  if (info.isDirectory()) {
    return path.join(collectionRoot, relative);
  }
  return targetDirectoryFor(sourcePath, collectionRoot).directory;
}

async function findGeneratedFiles(directory, extension) {
  const files = [];
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error.code === 'ENOENT') {
      return files;
    }
    throw error;
  }
  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== 'node_modules' && entry.name !== '.git') {
        files.push(...(await findGeneratedFiles(entryPath, extension)));
      }
    } else if (entry.isFile() && entry.name.endsWith(extension)) {
      const content = await readFile(entryPath, 'utf8');
      if (content.includes(MARKER)) {
        files.push(entryPath);
      }
    }
  }
  return files;
}

async function listFilesByExtension(directory, extension) {
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error.code === 'ENOENT') {
      return [];
    }
    throw error;
  }
  const files = [];
  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== 'node_modules' && entry.name !== '.git') {
        files.push(...(await listFilesByExtension(entryPath, extension)));
      }
    } else if (entry.isFile() && entry.name.endsWith(extension)) {
      files.push(entryPath);
    }
  }
  return files;
}

async function assertNoMixedFormats(collectionRoot, format) {
  const opposing = format === 'yml' ? '.bru' : '.yml';
  const files = await listFilesByExtension(collectionRoot, opposing);
  if (files.length > 0) {
    throw new Error(`Cannot write ${format} files into ${collectionRoot}: found ${files.length} ${opposing} file(s). Use a separate collection directory.`);
  }
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  await assertNoMixedFormats(args.collection, args.format);

  const files = await collectHttpFiles(args.source);
  if (files.length === 0) {
    usage(`No .http files found in ${args.source}`);
  }

  const expected = await buildExpected(files, args.collection, args.source, args.format);
  const ownedRoot = await ownedRootForSource(args.source, args.collection);
  const differences = [];
  const existingGenerated = await findGeneratedFiles(ownedRoot, args.format === 'yml' ? '.yml' : '.bru');

  for (const file of existingGenerated) {
    if (expected.has(file)) {
      continue;
    }
    differences.push(`stale: ${path.relative(args.collection, file)}`);
    if (!args.check) {
      await rm(file);
    }
  }

  for (const [file, content] of expected) {
    const relative = path.relative(args.collection, file);
    let current = null;
    try {
      current = await readFile(file, 'utf8');
    } catch (error) {
      if (error.code !== 'ENOENT') {
        throw error;
      }
    }
    if (current === content) {
      continue;
    }
    const managedYamlConfig = args.format === 'yml'
      && (file === path.join(args.collection, 'opencollection.yml')
        || file.startsWith(path.join(args.collection, 'environments') + path.sep));
    if (current !== null && !current.includes(MARKER) && !managedYamlConfig) {
      throw new Error(`Refusing to overwrite non-generated file: ${relative}`);
    }
    differences.push(`${current === null ? 'missing' : 'changed'}: ${relative}`);
    if (!args.check) {
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, content);
    }
  }

  if (differences.length === 0) {
    console.log(`Up to date: ${expected.size} file(s) from ${files.length} .http file(s).`);
    return;
  }

  const action = args.check ? 'Out of date' : 'Generated';
  console.log(`${action}: ${expected.size} file(s) from ${files.length} .http file(s).`);
  for (const difference of differences) {
    console.log(`  ${difference}`);
  }
  if (args.check) {
    process.exitCode = 1;
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
